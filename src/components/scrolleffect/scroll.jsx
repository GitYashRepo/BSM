export function ScrollCanvas() {
   const canvasRef = useRef(null)
   const containerRef = useRef(null)
   const imagesRef = useRef([])
   const currentFrameRef = useRef(0)
   const [imagesLoaded, setImagesLoaded] = useState(false)

   // Load all images
   useEffect(() => {
      let loadedCount = 0
      imagesRef.current = []

      IMAGE_URLS.forEach((url) => {
         const img = new Image()
         img.crossOrigin = 'anonymous'

         const handleLoad = () => {
            loadedCount++
            if (loadedCount === IMAGE_URLS.length) {
               setImagesLoaded(true)
            }
         }

         img.onload = handleLoad
         img.onerror = handleLoad
         img.src = url

         imagesRef.current.push(img)
      })
   }, [])

   // Setup canvas and scroll animation
   useEffect(() => {
      if (!imagesLoaded || !canvasRef.current || !containerRef.current) return

      const canvas = canvasRef.current
      const ctx = canvas.getContext('2d')
      if (!ctx) return

      const drawFrame = (frameIndex) => {
         const frame = Math.min(frameIndex, imagesRef.current.length - 1)
         const img = imagesRef.current[frame]

         if (!img || !img.complete || img.naturalWidth === 0) return

         ctx.clearRect(0, 0, canvas.width, canvas.height)

         const imgAspect = img.naturalWidth / img.naturalHeight
         const canvasAspect = canvas.width / canvas.height

         let drawWidth, drawHeight, offsetX, offsetY

         if (imgAspect > canvasAspect) {
            drawHeight = canvas.height
            drawWidth = drawHeight * imgAspect
            offsetX = (canvas.width - drawWidth) / 2
            offsetY = 0
         } else {
            drawWidth = canvas.width
            drawHeight = drawWidth / imgAspect
            offsetX = 0
            offsetY = (canvas.height - drawHeight) / 2
         }

         ctx.drawImage(img, offsetX, offsetY, drawWidth, drawHeight)
      }

      const updateCanvasSize = () => {
         canvas.width = window.innerWidth
         canvas.height = window.innerHeight
         drawFrame(currentFrameRef.current)
      }

      window.addEventListener('resize', updateCanvasSize)
      updateCanvasSize()

      const frameObj = { frame: 0 }

      const tween = gsap.to(frameObj, {
         frame: imagesRef.current.length - 1,
         ease: 'none',
         scrollTrigger: {
            trigger: containerRef.current,
            start: 'top top',
            end: `+=${window.innerHeight * 4}`,
            scrub: 0.5,
            pin: true,
            anticipatePin: 1,
         },
         onUpdate: () => {
            const frame = Math.round(frameObj.frame)
            if (frame !== currentFrameRef.current) {
               currentFrameRef.current = frame
               drawFrame(frame)
            }
         },
      })

      drawFrame(0)

      return () => {
         tween.scrollTrigger?.kill()
         tween.kill()
         window.removeEventListener('resize', updateCanvasSize)
      }
   }, [imagesLoaded])

   return (
      <>
         {/* Animation Section */}
         <div
            ref={containerRef}
            className="relative w-screen bg-black"
         >
            <div className="w-screen h-screen overflow-hidden bg-black">
               <canvas
                  ref={canvasRef}
                  className="w-full h-full block"
               />
            </div>
         </div>

         {/* Loading indicator */}
         {!imagesLoaded && (
            <div className="fixed inset-0 flex items-center justify-center bg-black z-50">
               <div className="flex flex-col items-center gap-4">
                  <div className="w-12 h-12 border-4 border-white/20 border-t-white rounded-full animate-spin" />
                  <p className="text-white text-sm">Loading animation...</p>
               </div>
            </div>
         )}
      </>
   )
}
